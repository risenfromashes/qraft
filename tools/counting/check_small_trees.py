#!/usr/bin/env python3
"""Exhaustive small-tree parity of the reference counting in shapes.py.

Binary unrooted labeled trees are generated by edge insertion. Contracting every
subset of internal edges then yields every arbitrary-degree topology. For each
topology, color-count compositions are sufficient: any concrete coloring is a
simultaneous relabeling of one block coloring, and the complete labeled topology
set is closed under that relabeling.

The default through six leaves is a fast CTest gate. The documented eight-leaf
enumeration is deterministically shardable, for example:

  for i in $(seq 0 255); do
    python3 -B tools/counting/check_small_trees.py \
      --max-leaves 8 --shard-count 256 --shard-index "$i" --seed 20260713
  done
"""
from __future__ import annotations

import argparse
import itertools
import sys
from collections import defaultdict, deque
from fractions import Fraction

import shapes as G


def link(adj, a, b):
    adj.setdefault(a, set()).add(b)
    adj.setdefault(b, set()).add(a)


def copy_adj(adj):
    return {node: set(neighbors) for node, neighbors in adj.items()}


def rooted_code(adj, node, parent):
    if isinstance(node, tuple):
        return f"L{node[1]}"
    children = sorted(rooted_code(adj, child, node)
                      for child in adj[node] if child != parent)
    return "(" + "".join(children) + ")"


def centers(adj):
    degree = {node: len(neighbors) for node, neighbors in adj.items()}
    leaves = deque(node for node, value in degree.items() if value <= 1)
    remaining = len(degree)
    while remaining > 2:
        for _ in range(len(leaves)):
            node = leaves.popleft()
            if degree[node] < 0:
                continue
            degree[node] = -1
            remaining -= 1
            for neighbor in adj[node]:
                if degree[neighbor] > 0:
                    degree[neighbor] -= 1
                    if degree[neighbor] == 1:
                        leaves.append(neighbor)
    return [node for node, value in degree.items() if value >= 0]


def canonical_topology(adj):
    return min(rooted_code(adj, center, None) for center in centers(adj))


def binary_topologies(max_leaves):
    center = -1
    initial = defaultdict(set)
    for leaf in range(3):
        link(initial, center, ("L", leaf))
    by_leaves = {3: {canonical_topology(initial): copy_adj(initial)}}
    for leaf_count in range(4, max_leaves + 1):
        generated = {}
        for adj in by_leaves[leaf_count - 1].values():
            edges = sorted(
                ((repr(a), repr(b), a, b)
                 for a, neighbors in adj.items() for b in neighbors
                 if repr(a) < repr(b)))
            for _, _, a, b in edges:
                out = copy_adj(adj)
                out[a].remove(b)
                out[b].remove(a)
                internal = min(node for node in out if isinstance(node, int)) - 1
                link(out, a, internal)
                link(out, internal, b)
                link(out, internal, ("L", leaf_count - 1))
                generated.setdefault(canonical_topology(out), out)
        by_leaves[leaf_count] = generated
    return by_leaves


def contract_internal_edges(adj, chosen):
    internal = [node for node in adj if isinstance(node, int)]
    parent = {node: node for node in internal}

    def find(node):
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    for a, b in chosen:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra
    out = defaultdict(set)
    for a, neighbors in adj.items():
        qa = find(a) if isinstance(a, int) else a
        for b in neighbors:
            qb = find(b) if isinstance(b, int) else b
            if qa != qb:
                link(out, qa, qb)
    return out


def all_contractions(binary):
    result = {}
    for adj in binary.values():
        internal_edges = sorted(
            (a, b) if a < b else (b, a)
            for a, neighbors in adj.items() if isinstance(a, int)
            for b in neighbors if isinstance(b, int) and a < b)
        for mask in range(1 << len(internal_edges)):
            chosen = [edge for bit, edge in enumerate(internal_edges)
                      if mask & (1 << bit)]
            contracted = contract_internal_edges(adj, chosen)
            result.setdefault(canonical_topology(contracted), contracted)
    return result


def compositions(total, parts):
    if parts == 1:
        yield (total,)
        return
    for first in range(total + 1):
        for rest in compositions(total - first, parts - 1):
            yield (first,) + rest


def block_colors(counts):
    colors = []
    for color, count in enumerate(counts):
        colors.extend([color] * count)
    return colors


def as_reference_tree(adj, colors, weights):
    tree = G.Tree()
    internal = sorted(node for node in adj if isinstance(node, int))
    root = internal[0]
    node_id = {node: index for index, node in enumerate(
        [("L", leaf) for leaf in range(len(colors))] + internal)}
    tree.root = node_id[root]

    def orient(node, parent):
        out_node = node_id[node]
        if isinstance(node, tuple):
            leaf = node[1]
            tree.leafinfo[out_node] = (colors[leaf], weights[leaf])
            return
        for child in sorted(adj[node], key=repr):
            if child == parent:
                continue
            tree.children[out_node].append(node_id[child])
            orient(child, node)

    orient(root, None)
    return tree


def weights_for(leaf_count, fractional, seed):
    if not fractional:
        return [Fraction(1) for _ in range(leaf_count)]
    return [Fraction(1 + ((seed + 5 * leaf) % 11),
                     1 + ((seed // 7 + 3 * leaf) % 7))
            for leaf in range(leaf_count)]


def run(args):
    if args.max_leaves < 4 or args.max_leaves > 8:
        raise ValueError("--max-leaves must be in [4,8]")
    if args.shard_count <= 0 or not 0 <= args.shard_index < args.shard_count:
        raise ValueError("invalid deterministic shard")

    binaries = binary_topologies(args.max_leaves)
    expected_binary = {3: 1, 4: 3, 5: 15, 6: 105, 7: 945, 8: 10395}
    checked = 0
    global_case = 0
    topology_counts = {}
    for leaf_count in range(4, args.max_leaves + 1):
        if len(binaries[leaf_count]) != expected_binary[leaf_count]:
            raise AssertionError(
                f"binary topology count n={leaf_count}: "
                f"{len(binaries[leaf_count])} != {expected_binary[leaf_count]}")
        topologies = all_contractions(binaries[leaf_count])
        topology_counts[leaf_count] = len(topologies)
        for topology_code in sorted(topologies):
            topology = topologies[topology_code]
            for palette in (2, 4):
                for counts in compositions(leaf_count, palette):
                    colors = block_colors(counts)
                    for fractional in (False, True):
                        case = global_case
                        global_case += 1
                        if case % args.shard_count != args.shard_index:
                            continue
                        weights = weights_for(leaf_count, fractional, args.seed)
                        tree = as_reference_tree(topology, colors, weights)
                        brute = dict(G.brute_force(tree, palette))
                        dynamic = dict(G.readout(G.eval_center_fold(tree), palette))
                        if brute != dynamic:
                            raise AssertionError(
                                "small-tree parity mismatch "
                                f"seed={args.seed} shard={args.shard_index}/"
                                f"{args.shard_count} case={case} n={leaf_count} "
                                f"K={palette} counts={counts} "
                                f"fractional={fractional} topology={topology_code} "
                                f"brute={brute} dp={dynamic}")
                        checked += 1
    print("small-tree exhaustive shard passed: "
          f"seed={args.seed} shard={args.shard_index}/{args.shard_count} "
          f"max_leaves={args.max_leaves} checked={checked}/"
          f"{global_case} topologies={topology_counts}")
    if checked == 0:
        raise AssertionError("selected shard contained no cases")
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-leaves", type=int, default=6)
    parser.add_argument("--shard-count", type=int, default=1)
    parser.add_argument("--shard-index", type=int, default=0)
    parser.add_argument("--seed", type=int, default=20260713)
    return run(parser.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
