"""Natural, minimal QRAFT WTA for k=2 and k=4.

Only linear projections and linear maps on child tensor products are used.
Each transition is generated by gluing explicit representative fragments.
"""
from fractions import Fraction
from itertools import combinations, combinations_with_replacement, product
from pathlib import Path
import argparse
import json
import random
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / 'code'))
import clusters as C


def path(adj, source, target):
    parent = {source: None}
    stack = [source]
    while stack:
        v = stack.pop()
        if v == target:
            result = []
            while v is not None:
                result.append(v)
                v = parent[v]
            return result[::-1]
        for w in adj[v]:
            if w not in parent:
                parent[w] = v
                stack.append(w)
    raise ValueError('Disconnected marked fragment')


def unrooted(code, attachment=None, colour=None):
    kinds, adj = C.graph_from_code(code)
    if attachment is not None:
        v = kinds.index(attachment)
        w = len(kinds)
        kinds.append(('L', colour))
        adj.append({v})
        adj[v].add(w)
    kinds = ['I' if k in ('T', 'B') else k for k in kinds]
    return C.canon(C.reduce_marked((kinds, adj)))


class NaturalWTA:
    def __init__(self, k):
        assert k in (2, 4)
        self.k = k
        self.channels = C.qraft_channels(k)
        self.labels, self.index, self.shapes, self.projection = {}, {}, {}, {}
        self.witnesses, self.transitions = {}, {}
        pairs = list(combinations_with_replacement(range(k), 2) if k == 2
                     else combinations(range(k), 2))
        for sort in ('C1', 'G', 'C2', 'T'):
            labels = []
            if sort != 'T':
                labels += [('unit',)] + [('leaf', c) for c in range(k)]
                for i, j in pairs:
                    if sort == 'C1':
                        geometries = ['all']
                    elif sort == 'G':
                        geometries = ['same', 'different']
                    else:
                        geometries = ['J', 'F', 'D'] if i == j else ['J', 'F', 'L', 'R']
                    labels += [('pair', i, j, g) for g in geometries]
                for side in (('T', 'B') if sort == 'C2' else ('T',)):
                    labels += [('triple', side, c, channel)
                               for c in range(k) for channel in self.channels]
            labels += [('quartet', channel) for channel in self.channels]
            self.labels[sort] = labels
            self.index[sort] = {label: i for i, label in enumerate(labels)}
            self.shapes[sort] = [s for degree in range(5) for s in C.fragments(sort, degree, k)]
            self.projection[sort] = {s: self.features(sort, s) for s in self.shapes[sort]}
            witnesses = [None] * len(labels)
            for s, features in self.projection[sort].items():
                if len(features) == 1:
                    i, value = next(iter(features.items()))
                    if value == 1 and witnesses[i] is None:
                        witnesses[i] = s
            assert all(s is not None for s in witnesses), (sort, witnesses)
            self.witnesses[sort] = witnesses
        for op, (_, inputs, output, _) in C.OPS.items():
            entries = []
            for indices in product(*(range(len(self.labels[s])) for s in inputs)):
                raw = tuple(self.witnesses[s][i] for s, i in zip(inputs, indices))
                result = C.ghat(op, raw)
                for target, coefficient in self.features(output, result).items():
                    assert coefficient == 1
                    entries.append([target, list(indices), coefficient])
            self.transitions[op] = entries

    def features(self, sort, code):
        if code is None:
            return {}
        degree = C.degree(code)
        features = []
        if degree == 4:
            closed = unrooted(code)
            features = [('quartet', name) for name, values in self.channels.items()
                        if values.get(closed, 0)]
        elif sort == 'T':
            return {}
        elif degree == 0:
            features = [('unit',)]
        elif degree == 1:
            features = [('leaf', next(iter(C.colours_of(code))))]
        elif degree == 2:
            kinds, adj = C.graph_from_code(code)
            leaves = sorted((k[1], v) for v, k in enumerate(kinds) if C.is_leaf_kind(k))
            (i, vi), (j, vj) = leaves
            if self.k == 4 and i == j:
                return {}
            if sort == 'C1':
                geometry = 'all'
            elif sort == 'G':
                t = kinds.index('T')
                geometry = 'same' if path(adj, t, vi)[1] == path(adj, t, vj)[1] else 'different'
            else:
                t, b = kinds.index('T'), kinds.index('B')
                spine = path(adj, t, b)
                position = {v: p for p, v in enumerate(spine)}
                def attach(leaf):
                    route = path(adj, leaf, t)
                    for p, v in enumerate(route):
                        if v in position:
                            return position[v], route[p - 1]
                    raise AssertionError
                pi, branch_i = attach(vi)
                pj, branch_j = attach(vj)
                if pi == pj:
                    geometry = 'J' if branch_i == branch_j else 'F'
                elif i == j:
                    geometry = 'D'
                else:
                    geometry = 'L' if pi < pj else 'R'
            features = [('pair', i, j, geometry)]
        elif degree == 3:
            for side in (('T', 'B') if sort == 'C2' else ('T',)):
                for colour in range(self.k):
                    closed = unrooted(code, side, colour)
                    features += [('triple', side, colour, name)
                                 for name, values in self.channels.items() if values.get(closed, 0)]
        return {self.index[sort][label]: 1 for label in features}

    def project(self, sort, raw):
        result = [Fraction(0)] * len(self.labels[sort])
        for code, weight in raw.items():
            for i, value in self.features(sort, code).items():
                result[i] += value * weight
        return result

    def evaluate(self, term):
        if term[0] == 'leaf':
            return self.project('C1', C.atom_state('leaf', term[1], term[2]))
        op = term[0]
        vectors = [self.evaluate(child) for child in term[1:]]
        output = C.OPS[op][2]
        result = [Fraction(0)] * len(self.labels[output])
        for target, indices, coefficient in self.transitions[op]:
            value = Fraction(coefficient)
            for vector, i in zip(vectors, indices):
                value *= vector[i]
            result[target] += value
        return result

    def export(self):
        return {
            'k': self.k, 'field': 'Q',
            'convention': 'Each binary transition is a linear map on the tensor product of its child spaces.',
            'coordinates': {s: [list(label) for label in labels] for s, labels in self.labels.items()},
            'witness_fragments': {s: [C.pretty(code) for code in codes] for s, codes in self.witnesses.items()},
            'transitions': self.transitions,
            'leaf_initializers': {str(c): {
                'constant': [str(v) for v in self.project('C1', C.atom_state('leaf', c, 0))],
                'weight_coefficient': [str(b-a) for a, b in zip(
                    self.project('C1', C.atom_state('leaf', c, 0)),
                    self.project('C1', C.atom_state('leaf', c, 1)))]}
                for c in range(self.k)},
            'transition_indexing': 'Zero based: [output coordinate, child coordinate indices, coefficient].',
            'readout': 'The T-sort vector is the output vector, in channel order.',
            'channels': list(self.channels),
        }


def verify(model):
    from minimal_model import MinimalModel
    certificates = HERE / 'certificates'
    old = MinimalModel(certificates / f'QRAFT{model.k}_K{model.k}.json')
    checked = 0
    profiles = {}
    for sort, labels in model.labels.items():
        assert len(labels) == len(old.rows[sort])
        # A natural row equals the old certified row combination determined by
        # its values on the old RREF pivot columns. Check every raw fragment.
        change_columns = [model.features(sort, s) for s in old.pivots[sort]]
        for code in model.shapes[sort]:
            reconstructed = {}
            for j, value in old.by_code[sort].get(code, []):
                for i, a in change_columns[j].items():
                    reconstructed[i] = reconstructed.get(i, 0) + a * value
            reconstructed = {i: v for i, v in reconstructed.items() if v}
            assert reconstructed == model.features(sort, code), (model.k, sort, C.pretty(code))
            checked += 1
        # Every natural coordinate has a pure witness. Thus the basis is
        # independent, and equality with the certified observable space follows.
        for i, code in enumerate(model.witnesses[sort]):
            assert model.features(sort, code) == {i: 1}
        profiles[sort] = [sum(C.degree(w) == d for w in model.witnesses[sort]) for d in range(5)]
    rng = random.Random(411 + model.k)
    term_checks = 0
    direct_checks = 0
    for sort in model.labels:
        for _ in range(12):
            term, cluster, raw = C.random_term(sort, model.k, rng,
                weights=lambda: rng.choice([Fraction(0), Fraction(-1), Fraction(2, 3), Fraction(2)]))
            assert model.evaluate(term) == model.project(sort, raw)
            term_checks += 1
            if len(cluster.leaves()) <= 9:
                assert model.evaluate(term) == model.project(sort, C.fragment_vector(cluster))
                direct_checks += 1
    return {
        'dimensions': {s: len(v) for s, v in model.labels.items()},
        'degree_profiles': profiles,
        'all_fragment_projection_checks': checked,
        'unit_column_witnesses': sum(map(len, model.labels.values())),
        'weighted_term_checks': term_checks,
        'direct_subset_checks': direct_checks,
        'transition_nonzeros': {op: len(entries) for op, entries in model.transitions.items()},
        'transition_coefficients': sorted({c for entries in model.transitions.values() for _, _, c in entries}),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--k', choices=[2, 4], type=int, nargs='+', default=[2, 4])
    args = parser.parse_args()
    records = {}
    for k in args.k:
        model = NaturalWTA(k)
        records[k] = verify(model)
        (HERE / f'qraft{k}_natural_wta.json').write_text(json.dumps(model.export(), indent=2) + '\n')
        print(k, json.dumps(records[k]), flush=True)
    (HERE / 'validation.json').write_text(json.dumps(records, indent=2) + '\n')


if __name__ == '__main__':
    main()
