"""Print the transition rules of the minimal automaton in the counter notation of
Brodal et al. (SODA'13, Sec. 7): n^X_i, n^X_{(ij)}, n^X_{ij}, n^X_{i^j} (arrow), n^X_{[z(yy')]},
the bottom-view counters, and q^X_a.  Input: qraft{k}_natural_wta.json.
Sorts: C1 = downward closed C, C2 = downward open C, G.  The rules for C3 (contains the root) and R
(the whole tree, read-out q_a) are generated by gen_c3_rules.py."""
import json, sys
from pathlib import Path
from collections import defaultdict

K = int(sys.argv[1]) if len(sys.argv) > 1 else 2
OUT = sys.argv[2] if len(sys.argv) > 2 else f'brodal_rules_k{K}.tex'
m = json.load(open(Path(__file__).resolve().parent / 'natwta' / f'qraft{K}_natural_wta.json'))
lab = {s: [tuple(l) for l in L] for s, L in m['coordinates'].items()}
# (inputs, output, names of the two arguments as superscripts, output superscript, title)
OPS = {
 'toG':       (('C1',),      'G',  ('C',),        'G', r'$\mathrm{C}\to\mathrm{G}$ (closed $\mathrm{C}$ becomes $\mathrm{G}$)'),
 'up_closed': (('G',),       'C1', ('G',),        'C', r'$\mathrm{IG}\to\mathrm{C}$, result $\mathrm{C}_1$ (downward closed)'),
 'up_open':   (('G',),       'C2', ('G',),        'C', r'$\mathrm{IG}\to\mathrm{C}$, result $\mathrm{C}_2$ (downward open)'),
 'sib':       (('G','G'),    'G',  ('G_1','G_2'), 'G', r'$\mathrm{GG}\to\mathrm{G}$'),
 'cat':       (('C2','C2'),  'C2', ("C'","C''"), 'C', r'$\mathrm{CC}\to\mathrm{C}$, lower part downward open: result $\mathrm{C}_2$'),
 'cap':       (('C2','C1'),  'C1', ("C'","C''"), 'C', r'$\mathrm{CC}\to\mathrm{C}$, lower part downward closed: result $\mathrm{C}_1$'),
}

def triple_pattern(x, a):
    """channel a = 'ij|xy'; test colour x on one side: z = partner of x, (yy') = other side"""
    A, B = a.split('|')
    x = str(x)
    if x in A:
        z = A.replace(x, '', 1); yy = B
    else:
        z = B.replace(x, '', 1); yy = A
    return z, yy

def sym(l, sup):
    """Brodal-style symbol for coordinate label l of a component with superscript sup"""
    kind = l[0]
    if kind == 'unit':
        return '1'
    if kind == 'leaf':
        return f'n^{{{sup}}}_{{{l[1]}}}'
    if kind == 'pair':
        i, j, g = l[1], l[2], l[3]
        if g == 'all':        return f'n^{{{sup}}}_{{[{i}{j}]}}'
        if g == 'same':       return f'n^{{{sup}}}_{{({i}{j})}}'
        if g == 'different':  return f'n^{{{sup}}}_{{{i}{j}}}'
        if g == 'J':          return f'n^{{{sup}}}_{{({i}{j})}}'
        if g == 'F':          return f'n^{{{sup}}}_{{{i}{j}}}'
        if g == 'L':          return f'n^{{{sup}}}_{{{j}\\uparrow {i}}}'   # i above j  -> j lower
        if g == 'R':          return f'n^{{{sup}}}_{{{i}\\uparrow {j}}}'
        if g == 'D':          return f'n^{{{sup}}}_{{{i}\\uparrow {i}}}'
    if kind == 'triple':
        side, x, a = l[1], l[2], l[3]
        z, yy = triple_pattern(x, a)
        core = f'[{z}({yy})]'
        return f'n^{{{sup}}}_{{{core}}}' if side == 'T' else f'n^{{{sup}}}_{{\\downarrow{core}}}'
    if kind == 'quartet':
        return f'q^{{{sup}}}_{{{l[1]}}}'

def chunks(seq, n):
    for i in range(0, len(seq), n):
        yield seq[i:i+n]

out = []
for op in ('toG', 'up_closed', 'up_open', 'sib', 'cap', 'cat'):
    # ('close', the whole-tree read-out of the package, is not a symbol here: the answer is q_a of the last C)
    ins, o, sups, osup, title = OPS[op]
    by = defaultdict(list)
    for tgt, idx, c in m['transitions'][op]:
        assert c == 1
        by[tgt].append(idx)
    out.append(f'\\subsubsection*{{{title}}}')
    lines = []
    for tgt in range(len(lab[o])):
        lhs_lab = lab[o][tgt]
        if lhs_lab[0] == 'unit':
            continue                      # the constant 1 needs no rule
        lhs = sym(lhs_lab, osup)
        terms = []
        for idx in by[tgt]:
            if len(ins) == 1:
                t = sym(lab[ins[0]][idx[0]], sups[0])
                terms.append(t)
            else:
                a = sym(lab[ins[0]][idx[0]], sups[0]); b = sym(lab[ins[1]][idx[1]], sups[1])
                if a == '1' and b == '1': terms.append('1')
                elif a == '1': terms.append(b)
                elif b == '1': terms.append(a)
                else: terms.append(a + '\\,' + b)
        if not terms:
            lines.append(f'{lhs} &= 0')
            continue
        parts = list(chunks(terms, 3 if len(ins) == 2 else 5))
        rhs = ' \\\\\n &\\quad + '.join(' + '.join(p) for p in parts)
        lines.append(f'{lhs} &= {rhs}')
    out.append('\\begin{align*}\n' + ' \\\\\n'.join(lines) + '\n\\end{align*}')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT)
